namespace Sellora.DeliveryService.Application.Events;

public record DeliveryStatusChangedEvent(
    Guid EventId,
    string EventType,
    Guid CompanyId,
    Guid DeliveryJobId,
    string DeliveryReference,
    Guid OrderId,
    string OrderReference,
    string FulfilmentType,
    Guid AgencyId,
    string AgencyName,
    Guid ShopId,
    string ShopName,
    string Status,
    Guid? AssignedRepId,
    string? AssignedRepName,
    DateOnly? ScheduledDate,
    DateTimeOffset? DeliveredAt,
    DateTimeOffset OccurredAt)
{
    public static DeliveryStatusChangedEvent Create(
        Guid companyId,
        Guid deliveryJobId,
        string deliveryReference,
        Guid orderId,
        string orderReference,
        string fulfilmentType,
        Guid agencyId,
        string agencyName,
        Guid shopId,
        string shopName,
        string status,
        Guid? assignedRepId,
        string? assignedRepName,
        DateOnly? scheduledDate,
        DateTimeOffset? deliveredAt,
        DateTimeOffset occurredAt)
        => new(
            EventId: Guid.NewGuid(),
            EventType: "DeliveryStatusChanged",
            CompanyId: companyId,
            DeliveryJobId: deliveryJobId,
            DeliveryReference: deliveryReference,
            OrderId: orderId,
            OrderReference: orderReference,
            FulfilmentType: fulfilmentType,
            AgencyId: agencyId,
            AgencyName: agencyName,
            ShopId: shopId,
            ShopName: shopName,
            Status: status,
            AssignedRepId: assignedRepId,
            AssignedRepName: assignedRepName,
            ScheduledDate: scheduledDate,
            DeliveredAt: deliveredAt,
            OccurredAt: occurredAt);
}
